def _build_chains(arsenal: dict) -> dict:
    """Deterministic new-chain factory: per-class + per-category-full + curated."""
    out = {}
    by_class = {}
    for name, (cap, classes, plan, tpl) in arsenal.items():
        if isinstance(classes, (list, tuple, set)):
            for c in classes:
                by_class.setdefault(c, []).append(name)
    for cls in _CLASS_CHAIN_ORDER:
        tools = by_class.get(cls, [])
        if tools:
            out[f"cls-{cls}"] = tools[:8]
    for name in sorted(by_class):
        out[f"{name}-full"] = sorted(by_class[name])[:10]
    out.update(_CURATED_CHAINS)
    return out